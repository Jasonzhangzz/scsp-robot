"""Frozen-state temperature and amplitude-clip study for the softplus benchmark.

One GPU contact assembly per raw state; independent float64 NumPy impulses for
all variants. The reference trajectory is never regenerated by a candidate.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import benchmark_velocity_error as benchmark
from benchmark_utils import Backend
import numpy as np


def smooth_clip_lse(x, epsilon=.01):
    # Integral of a sigmoid-window; symmetry avoids cancellation for x >> 1.
    if x <= .5:
        return float(epsilon*(np.logaddexp(0., x/epsilon)-np.logaddexp(0., (x-1)/epsilon)))
    return float(1-epsilon*(np.logaddexp(0., (1-x)/epsilon)-np.logaddexp(0., -x/epsilon)))


def smooth_clip_c1(x, epsilon=.01):
    """C1 rounded clip, with exact zero for x<=0 and 0<=result<=min(x,1)."""
    if x <= 0:
        return 0.
    if x < epsilon:
        t = x/epsilon
        return float(epsilon*(2*t*t-t*t*t))
    if x <= 1-epsilon:
        return float(x)
    if x < 1+epsilon:
        return float(1-(1+epsilon-x)**2/(4*epsilon))
    return 1.


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    raw = json.loads(args.source.read_text())
    assert raw['soft_scm_corrected']['law_version'] == 'softplus_impulse_v1'
    variants = [('hard_max', 0., 'hard'), ('T_1e-5', 1e-5, 'hard'),
                ('T_1e-4', 1e-4, 'hard'), ('T_1e-3', 1e-3, 'hard'),
                ('T_1e-4_lse_clip', 1e-4, 'lse'), ('T_1e-4_c1_clip', 1e-4, 'c1')]
    records = []
    max_velocity_difference = 0.
    for shape in raw['objects']:
        model = benchmark.make_model(shape, raw['friction'], raw['h_model'], raw['mass'])
        settled = benchmark.settle(model)
        backend = Backend('scm_soft_corrected', model, settled, nconmax=512, njmax=4096)
        for row in (r for r in raw['rows'] if r['object'] == shape):
            prediction, data = benchmark.step_backend(backend, model, np.asarray(row['qpos_initial']),
                np.asarray(row['qvel_initial']), np.asarray(row['wrench_world_N_Nm']))
            np.testing.assert_allclose(prediction, row['prediction_velocity_world']['softSCM_corrected'],
                                       atol=5e-5, rtol=1e-4)
            count = int(backend.wdata.nefc.numpy()[0])
            J = backend.wdata.efc.J.numpy()[0, :count, :6].astype(float)
            gap = backend.wdata.efc.efc_dist.numpy()[0, :count].astype(float)
            free = backend.wdata.qvel_smooth_pred.numpy()[0, :6].astype(float)
            inverse = (np.diag(backend.api.inverse_diagonal.numpy().astype(float)) if backend.api.use_diagonal
                       else backend.api.inverse_dense.numpy().astype(float))
            W = J@inverse@J.T+1e-8*np.eye(count)
            g = J@free+gap/raw['h_model']
            rotation = np.zeros(9)
            benchmark.mujoco.mju_quat2Mat(rotation, np.asarray(row['qpos_initial'][3:]))
            rotation = rotation.reshape(3, 3)
            for name, temperature, clip in variants:
                trial = -g/np.diag(W)
                p = (np.maximum(trial, 0.) if temperature == 0 else
                     temperature*np.logaddexp(0., trial/temperature))
                numerator, denominator = float(g@p), float(p@W@p)
                x = -numerator/denominator if denominator > 0 else 1.
                alpha = (float(np.clip(x, 0, 1)) if clip == 'hard' else
                         smooth_clip_lse(x) if clip == 'lse' else smooth_clip_c1(x))
                velocity = free+inverse@J.T@(alpha*p)
                world = np.r_[velocity[:3], rotation@velocity[3:]]
                if name == 'T_1e-4':
                    max_velocity_difference = max(max_velocity_difference, float(np.max(np.abs(world-prediction))))
                    np.testing.assert_allclose(world, prediction, atol=5e-5, rtol=1e-4)
                linear, angular = benchmark.errors(world, np.asarray(row['reference_velocity_world']))
                records.append(dict(object=shape, condition=row['condition'], sample=row['sample'], step=row['step'],
                                    variant=name, linear=linear, angular=angular, alpha=alpha, alpha_unclipped=x,
                                    quadratic_change_from_free=.5*alpha*alpha*denominator+alpha*numerator))
        print('analyzed', shape, flush=True)
    summary = {}
    for name, _, _ in variants:
        selected = [r for r in records if r['variant'] == name]
        summary[name] = {condition: {metric: benchmark.stats(r[metric] for r in selected if r['condition'] == condition)
                                    for metric in ('linear', 'angular')} for condition in benchmark.CONDITIONS}
        summary[name]['objective_increases_gt_1e-12'] = sum(r['quadratic_change_from_free'] > 1e-12 for r in selected)
        summary[name]['unclipped_alpha_le_zero'] = sum(r['alpha_unclipped'] <= 0 for r in selected)
    payload = dict(source=str(args.source), source_sha256=hashlib.sha256(args.source.read_bytes()).hexdigest(),
                   method='frozen-state NumPy formula using GPU contact geometry/smooth dynamics; all raw states',
                   n_states=len(raw['rows']), clip_epsilon=.01, max_numpy_gpu_velocity_difference=max_velocity_difference,
                   summary=summary, rows=records)
    output = args.source.parent/'softplus_sensitivity.json'
    output.write_text(json.dumps(payload)+'\n')
    print('wrote', output, flush=True)
    for name, _, _ in variants:
        print(name, summary[name], flush=True)


if __name__ == '__main__':
    main()
